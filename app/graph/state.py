"""State definition for the Autonomous Code & Analysis Workspace.

Tracks the full lifecycle of the multi-agent orchestration:
- User intent and requirements
- Execution artifacts (code, stdout, stderr, exit codes)
- Debugging feedback and error traces
- Iteration counters and safety circuit breakers
"""

from typing import TypedDict, Optional, List, Annotated
import operator
from pydantic import BaseModel, Field


class AgentState(TypedDict):
    """The central LangGraph State passed across all agent nodes.
    
    Using TypedDict ensures compatibility with LangGraph's state graph reducer model.
    The execution_logs field uses `operator.add` so nodes can append log messages
    monotonically without overwriting previous history.
    """

    # User Query & Requirements
    user_query: str

    # Architecture & Plan
    plan: Optional[str]

    # Code Artifacts
    generated_code: Optional[str]

    # Runtime Execution Results
    stdout: Optional[str]
    stderr: Optional[str]
    exit_code: Optional[int]
    error_trace: Optional[str]

    # Debugging & Iteration Feedback
    review_feedback: Optional[str]

    # Iteration Guardrails (Circuit Breaker)
    iteration_count: int
    max_iterations: int

    # Monotonically appended audit log
    execution_logs: Annotated[List[str], operator.add]

    # Workflow Status & Final Synthesis
    status: str
    final_result: Optional[str]


class AgentStateModel(BaseModel):
    """Pydantic representation of the AgentState for API I/O and strict schema validation."""
    user_query: str = Field(..., description="Original user prompt or analysis question")
    plan: Optional[str] = Field(None, description="Step-by-step strategy generated by planner")
    generated_code: Optional[str] = Field(None, description="Latest Python source code script")
    stdout: Optional[str] = Field(None, description="Captured stdout from sandbox container")
    stderr: Optional[str] = Field(None, description="Captured stderr from sandbox container")
    exit_code: Optional[int] = Field(None, description="Docker process exit status code")
    error_trace: Optional[str] = Field(None, description="Filtered exception or stack trace")
    review_feedback: Optional[str] = Field(None, description="Correction guidance from reviewer")
    iteration_count: int = Field(default=0, description="Current number of execution attempts")
    max_iterations: int = Field(default=5, description="Maximum allowed iterations before aborting")
    execution_logs: List[str] = Field(default_factory=list, description="Audit trail of agent actions")
    status: str = Field(default="initialized", description="Current workflow state")
    final_result: Optional[str] = Field(None, description="Final user-facing answer or synthesis")

